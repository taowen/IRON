#!/usr/bin/env python3
"""Derive the exact Q4NX section rewrite contract from exp120 and exp121."""

from __future__ import annotations

import argparse
import json
from dataclasses import dataclass
from pathlib import Path

EXPERIMENT_DIR = Path(__file__).resolve().parent
REPO_ROOT = EXPERIMENT_DIR.parents[1]
CONTRACT_JSON = REPO_ROOT / "experiments/120_mylm_q4nx_generator_contract/mylm_q4nx_generator_contract.json"
NUMERIC_JSON = REPO_ROOT / "experiments/121_q4nx_modified_body_numeric_gate/q4nx_modified_body_numeric_gate.json"
DEFAULT_REPORT = EXPERIMENT_DIR / "q4nx_exact_section_rewrite_contract.md"
DEFAULT_JSON = EXPERIMENT_DIR / "q4nx_exact_section_rewrite_contract.json"
DEFAULT_ASM_INC = EXPERIMENT_DIR / "generated_q4nx_exact_section_rewrite.s.inc"

GROUPS = 8


@dataclass(frozen=True)
class SourceSection:
    name: str
    groups: tuple[int, ...]
    template_group: int
    source_macs_per_group: int
    live_in_boundary: int | None
    live_out_boundary: int | None


@dataclass(frozen=True)
class RewriteSection:
    name: str
    macro: str
    groups: tuple[int, ...]
    template_group: int
    source_macs_per_group: int
    exact_macs_per_group: int
    removed_zero_macs_per_group: int
    live_in_boundary: int | None
    live_out_boundary: int | None


@dataclass(frozen=True)
class NumericGate:
    exact_max_abs: float
    exact_mismatches_1e_2: int
    mylm_stress_max_abs: float
    mylm_stress_mismatches_1e_2: int


@dataclass(frozen=True)
class RewriteCheck:
    sections: int
    source_static_macs: int
    exact_static_macs: int
    removed_zero_macs: int
    exact_dynamic_macs: int
    exact_gate_passes: bool
    mylm_stress_gate_passes: bool


def load_json(path: Path):
    return json.loads(path.read_text())


def source_sections(contract) -> tuple[SourceSection, ...]:
    sections: list[SourceSection] = []
    for item in contract["sections"]:
        sections.append(
            SourceSection(
                name=str(item["name"]),
                groups=tuple(int(group) for group in item["groups"]),
                template_group=int(item["template_group"]),
                source_macs_per_group=int(item["macs_per_group"]),
                live_in_boundary=item["live_in_boundary"],
                live_out_boundary=item["live_out_boundary"],
            )
        )
    return tuple(sections)


def rewrite_sections(sections: tuple[SourceSection, ...]) -> tuple[RewriteSection, ...]:
    rewritten: list[RewriteSection] = []
    for section in sections:
        rewritten.append(
            RewriteSection(
                name=section.name,
                macro=f"Q4NX_EXACT_{section.name.upper()}",
                groups=section.groups,
                template_group=section.template_group,
                source_macs_per_group=section.source_macs_per_group,
                exact_macs_per_group=section.source_macs_per_group - 1,
                removed_zero_macs_per_group=1,
                live_in_boundary=section.live_in_boundary,
                live_out_boundary=section.live_out_boundary,
            )
        )
    return tuple(rewritten)


def numeric_gate(numeric) -> NumericGate:
    exact_stats = [
        item
        for item in numeric["stats"]
        if item["name"] == "exact_recompose_coeff"
    ]
    mylm_stress = next(
        item
        for item in numeric["stats"]
        if item["name"] == "mylm_group_correction" and item["scenario"] == "stress"
    )
    return NumericGate(
        exact_max_abs=max(float(item["max_abs"]) for item in exact_stats),
        exact_mismatches_1e_2=sum(int(item["mismatches_1e_2"]) for item in exact_stats),
        mylm_stress_max_abs=float(mylm_stress["max_abs"]),
        mylm_stress_mismatches_1e_2=int(mylm_stress["mismatches_1e_2"]),
    )


def check_rewrite(sections: tuple[RewriteSection, ...], gate: NumericGate) -> RewriteCheck:
    source_static = sum(len(section.groups) * section.source_macs_per_group for section in sections)
    exact_static = sum(len(section.groups) * section.exact_macs_per_group for section in sections)
    removed = sum(len(section.groups) * section.removed_zero_macs_per_group for section in sections)
    return RewriteCheck(
        sections=len(sections),
        source_static_macs=source_static,
        exact_static_macs=exact_static,
        removed_zero_macs=removed,
        exact_dynamic_macs=exact_static * 2,
        exact_gate_passes=gate.exact_mismatches_1e_2 == 0,
        mylm_stress_gate_passes=gate.mylm_stress_mismatches_1e_2 == 0,
    )


def live_name(boundary: int | None, exit_name: str) -> str:
    if boundary is None:
        return exit_name
    return f"boundary{boundary}"


def render_asm_inc(sections: tuple[RewriteSection, ...]) -> str:
    lines = [
        "// Generated by exp122 from the exp120 section contract and exp121 numeric gate.",
        "// This include is a rewrite contract, not production assembly.",
        "// Each section removes one MyLM zero-correction MAC per logical group.",
        "",
    ]
    for section in sections:
        lines.extend(
            [
                f".macro {section.macro}",
                f"\t// section {section.name}",
                f"\t// source_macs_per_group={section.source_macs_per_group}",
                f"\t// exact_macs_per_group={section.exact_macs_per_group}",
                f"\t// removed_zero_macs_per_group={section.removed_zero_macs_per_group}",
                f"\t// live_in={live_name(section.live_in_boundary, 'entry')}",
                f"\t// live_out={live_name(section.live_out_boundary, 'exit')}",
                "\t// generator must emit exact_recompose_coeff before each MAC",
                ".endm",
                "",
            ]
        )
    lines.append(".macro Q4NX_EXACT_SECTION_REWRITE_BODY")
    for section in sections:
        for group in section.groups:
            lines.append(f"\t// group{group}")
            lines.append(f"\t{section.macro}")
    lines.append(".endm")
    lines.append("")
    return "\n".join(lines)


def section_to_json(section: RewriteSection):
    return {
        "name": section.name,
        "macro": section.macro,
        "groups": list(section.groups),
        "template_group": section.template_group,
        "source_macs_per_group": section.source_macs_per_group,
        "exact_macs_per_group": section.exact_macs_per_group,
        "removed_zero_macs_per_group": section.removed_zero_macs_per_group,
        "live_in_boundary": section.live_in_boundary,
        "live_out_boundary": section.live_out_boundary,
    }


def render_json(sections: tuple[RewriteSection, ...], gate: NumericGate, check: RewriteCheck):
    return {
        "sections": [section_to_json(section) for section in sections],
        "numeric_gate": gate.__dict__,
        "checks": check.__dict__,
    }


def render_report(sections: tuple[RewriteSection, ...], gate: NumericGate, check: RewriteCheck) -> str:
    lines = [
        "# Q4NX Exact Section Rewrite Contract",
        "",
        "This experiment turns the exp121 exact-body decision into a section-level",
        "rewrite contract. It keeps exp120's live-state boundaries and removes one",
        "MyLM zero-correction MAC from each logical group.",
        "",
        "## Checks",
        "",
        f"- Sections: `{check.sections}`",
        f"- Source static MACs: `{check.source_static_macs}`",
        f"- Exact static MACs: `{check.exact_static_macs}`",
        f"- Removed zero-correction MACs: `{check.removed_zero_macs}`",
        f"- Exact dynamic MACs: `{check.exact_dynamic_macs}`",
        f"- Exact synthetic gate passes: `{check.exact_gate_passes}`",
        f"- MyLM stress gate passes: `{check.mylm_stress_gate_passes}`",
        "",
        "## Numeric Gate Inputs",
        "",
        f"- Exact max abs: `{gate.exact_max_abs:.9f}`",
        f"- Exact `>1e-2`: `{gate.exact_mismatches_1e_2}`",
        f"- MyLM-like stress max abs: `{gate.mylm_stress_max_abs:.9f}`",
        f"- MyLM-like stress `>1e-2`: `{gate.mylm_stress_mismatches_1e_2}`",
        "",
        "## Section Rewrite",
        "",
        "| Section | Groups | Source MACs/group | Exact MACs/group | Live In | Live Out |",
        "| --- | --- | ---: | ---: | --- | --- |",
    ]
    for section in sections:
        groups = ",".join(str(group) for group in section.groups)
        lines.append(
            f"| `{section.name}` | `{groups}` | {section.source_macs_per_group} | "
            f"{section.exact_macs_per_group} | `{live_name(section.live_in_boundary, 'entry')}` | "
            f"`{live_name(section.live_out_boundary, 'exit')}` |"
        )
    lines.extend(
        [
            "",
            "## Generated Include",
            "",
            f"- `{DEFAULT_ASM_INC}`",
            "",
            "## Production Implication",
            "",
            "- The next source-assembly generator should use this rewrite contract, not the MyLM 33-MAC/group contract.",
            "- It must preserve exp120 section live state while emitting exact coefficient recomposition before each MAC.",
            "- MyLM-like group correction remains a separate quality/performance branch gated by real token tests.",
        ]
    )
    return "\n".join(lines) + "\n"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--json-output", type=Path, default=DEFAULT_JSON)
    parser.add_argument("--asm-inc", type=Path, default=DEFAULT_ASM_INC)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    contract = load_json(CONTRACT_JSON)
    numeric = load_json(NUMERIC_JSON)
    sections = rewrite_sections(source_sections(contract))
    gate = numeric_gate(numeric)
    check = check_rewrite(sections, gate)
    args.asm_inc.write_text(render_asm_inc(sections))
    args.json_output.write_text(json.dumps(render_json(sections, gate, check), indent=2) + "\n")
    args.report.write_text(render_report(sections, gate, check))
    print(f"wrote {args.report}")
    print(f"wrote {args.json_output}")
    print(f"wrote {args.asm_inc}")
    print(f"source_static_macs={check.source_static_macs}")
    print(f"exact_static_macs={check.exact_static_macs}")
    print(f"removed_zero_macs={check.removed_zero_macs}")
    print(f"exact_gate_passes={check.exact_gate_passes}")
    return 0 if check.exact_static_macs == 256 and check.exact_gate_passes else 1


if __name__ == "__main__":
    raise SystemExit(main())
