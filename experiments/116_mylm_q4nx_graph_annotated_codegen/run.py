#!/usr/bin/env python3
"""Generate a MyLM steady template annotated from the operand graph JSON."""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from dataclasses import dataclass
from difflib import unified_diff
from pathlib import Path
from types import ModuleType

EXPERIMENT_DIR = Path(__file__).resolve().parent
REPO_ROOT = EXPERIMENT_DIR.parents[1]
EXP104_RUN = REPO_ROOT / "experiments/104_mylm_q4nx_pipeline_schedule/run.py"
GRAPH_JSON = REPO_ROOT / "experiments/115_mylm_q4nx_operand_graph/mylm_q4nx_operand_graph.json"
DEFAULT_REPORT = EXPERIMENT_DIR / "mylm_q4nx_graph_annotated_codegen.md"
DEFAULT_ASM_INC = EXPERIMENT_DIR / "generated_mylm_q4nx_steady_graph.s.inc"
STEADY_GROUP = 1
STEADY_BOUNDARY_GROUPS = (2, 3, 4, 5, 6)


@dataclass(frozen=True)
class GraphCheck:
    group1_slots: int
    group1_vmac: int
    graph_vmac: int
    exact_instruction_match: bool
    stable_steady_boundary: bool
    steady_boundary_hash: str


def load_exp104() -> ModuleType:
    spec = importlib.util.spec_from_file_location("exp104_pipeline_schedule", EXP104_RUN)
    if spec is None or spec.loader is None:
        raise ValueError(f"cannot load {EXP104_RUN}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def slot_label(slot) -> str:
    return f"g{slot.group}@0x{slot.address:x}.{slot.bundle_slot}:{slot.op}"


def load_graph(path: Path):
    return json.loads(path.read_text())


def graph_by_slot(graph):
    return {record["slot"]: record for record in graph["steady_group_macs"]}


def boundary_hashes(graph) -> dict[int, str]:
    return {int(record["group"]): str(record["signature_hash"]) for record in graph["boundaries"]}


def format_cells(operand) -> str:
    parts: list[str] = []
    for cell in operand["cells"]:
        lane = cell["lane"] if cell["lane"] is not None else ""
        parts.append(f"{cell['cell']}:{cell['kind']}{lane}")
    return ", ".join(parts)


def graph_comment(record) -> str:
    return (
        f"// graph {record['slot']} "
        f"acc=[{format_cells(record['accumulator'])}] "
        f"left=[{format_cells(record['left'])}] "
        f"right=[{format_cells(record['right'])}]"
    )


def render_asm_inc(group_slots: list, graph_records) -> str:
    lines = [
        "// Generated by exp116 from exp115 operand graph JSON and MyLM group1 disasm.",
        "// Instruction lines must match MyLM group1 after comments are stripped.",
        "",
        ".macro MYLM_Q4NX_STEADY_GRAPH",
    ]
    for slot in group_slots:
        label = slot_label(slot)
        if slot.op == "vmac.f":
            record = graph_records.get(label)
            if record is None:
                raise ValueError(f"missing graph record for {label}")
            lines.append(f"\t{graph_comment(record)}")
        lines.append(f"\t{slot.text}")
    lines.append(".endm")
    lines.append("")
    return "\n".join(lines)


def strip_generated_instructions(text: str) -> list[str]:
    instructions: list[str] = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("//") or line.startswith(".macro") or line == ".endm":
            continue
        instructions.append(line)
    return instructions


def validate(group_slots: list, graph, asm_text: str) -> GraphCheck:
    graph_records = graph_by_slot(graph)
    original = [slot.text for slot in group_slots]
    generated = strip_generated_instructions(asm_text)
    hashes = boundary_hashes(graph)
    steady_hash_values = [hashes[group] for group in STEADY_BOUNDARY_GROUPS]
    return GraphCheck(
        group1_slots=len(group_slots),
        group1_vmac=sum(1 for slot in group_slots if slot.op == "vmac.f"),
        graph_vmac=len(graph_records),
        exact_instruction_match=original == generated,
        stable_steady_boundary=len(set(steady_hash_values)) == 1,
        steady_boundary_hash=steady_hash_values[0],
    )


def render_report(check: GraphCheck, group_slots: list, graph, asm_text: str) -> str:
    graph_records = graph_by_slot(graph)
    missing = [slot_label(slot) for slot in group_slots if slot.op == "vmac.f" and slot_label(slot) not in graph_records]
    original = [slot.text for slot in group_slots]
    generated = strip_generated_instructions(asm_text)
    lines = [
        "# MyLM Q4NX Graph-Annotated Codegen",
        "",
        "This experiment consumes the exp115 JSON operand graph and emits a",
        "steady-state assembly include with generated half-register comments.",
        "",
        "## Checks",
        "",
        f"- Group1 slots: `{check.group1_slots}`",
        f"- Group1 `vmac.f`: `{check.group1_vmac}`",
        f"- Graph `vmac.f` records: `{check.graph_vmac}`",
        f"- Instruction text match after stripping comments: `{check.exact_instruction_match}`",
        f"- Stable steady boundary: `{check.stable_steady_boundary}`",
        f"- Steady boundary hash: `{check.steady_boundary_hash}`",
        f"- Missing graph records: `{len(missing)}`",
        "",
        "## Generated Include",
        "",
        f"- `{DEFAULT_ASM_INC}`",
        "",
        "## Why This Matters",
        "",
        "- The generated include proves exp115 is a usable generator input, not only a report.",
        "- Each `vmac.f` now carries machine-generated half-register state next to the instruction that consumes it.",
        "- The next step is to generate a modified body from graph records and run a numeric gate, rather than manually editing raw assembly.",
    ]
    if missing:
        lines.extend(["", "## Missing Records", ""])
        for item in missing:
            lines.append(f"- `{item}`")
    if not check.exact_instruction_match:
        lines.extend(["", "## First Diff", "", "```diff"])
        lines.extend(list(unified_diff(original, generated, fromfile="mylm_group1", tofile="generated", n=4))[:120])
        lines.append("```")
    return "\n".join(lines) + "\n"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--graph-json", type=Path, default=GRAPH_JSON)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--asm-inc", type=Path, default=DEFAULT_ASM_INC)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    exp104 = load_exp104()
    slots = exp104.parse_slots(exp104.DEFAULT_DISASM)
    group_slots = [slot for slot in slots if slot.group == STEADY_GROUP]
    graph = load_graph(args.graph_json)
    asm_text = render_asm_inc(group_slots, graph_by_slot(graph))
    check = validate(group_slots, graph, asm_text)
    args.asm_inc.write_text(asm_text)
    args.report.write_text(render_report(check, group_slots, graph, asm_text))
    print(f"wrote {args.report}")
    print(f"wrote {args.asm_inc}")
    print(f"group1_slots={check.group1_slots}")
    print(f"group1_vmac={check.group1_vmac}")
    print(f"graph_vmac={check.graph_vmac}")
    print(f"exact_instruction_match={check.exact_instruction_match}")
    print(f"steady_boundary_hash={check.steady_boundary_hash}")
    return 0 if check.exact_instruction_match and check.group1_vmac == check.graph_vmac else 1


if __name__ == "__main__":
    raise SystemExit(main())
