#!/usr/bin/env python3
"""Generate the full MyLM Q4NX hot loop with graph annotations."""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import sys
from collections import Counter
from dataclasses import dataclass
from difflib import unified_diff
from pathlib import Path
from types import ModuleType

EXPERIMENT_DIR = Path(__file__).resolve().parent
REPO_ROOT = EXPERIMENT_DIR.parents[1]
EXP104_RUN = REPO_ROOT / "experiments/104_mylm_q4nx_pipeline_schedule/run.py"
GRAPH_JSON = REPO_ROOT / "experiments/115_mylm_q4nx_operand_graph/mylm_q4nx_operand_graph.json"
DEFAULT_REPORT = EXPERIMENT_DIR / "mylm_q4nx_full_graph_codegen.md"
DEFAULT_ASM_INC = EXPERIMENT_DIR / "generated_mylm_q4nx_hot_loop_graph.s.inc"
STEADY_REPEATS = 5


@dataclass(frozen=True)
class GeneratedSlot:
    section: str
    text: str
    op: str
    group1_label: str | None


@dataclass(frozen=True)
class FullGraphCheck:
    original_slots: int
    generated_slots: int
    original_hash: str
    generated_hash: str
    exact_instruction_match: bool
    graph_records: int
    annotated_vmac: int
    missing_graph_records: tuple[str, ...]
    steady_boundary_hash: str
    op_counts: Counter[str]


def load_exp104() -> ModuleType:
    spec = importlib.util.spec_from_file_location("exp104_pipeline_schedule", EXP104_RUN)
    if spec is None or spec.loader is None:
        raise ValueError(f"cannot load {EXP104_RUN}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def digest(lines: list[str]) -> str:
    return hashlib.sha256("\n".join(lines).encode()).hexdigest()


def slot_label(slot) -> str:
    return f"g{slot.group}@0x{slot.address:x}.{slot.bundle_slot}:{slot.op}"


def load_graph(path: Path):
    return json.loads(path.read_text())


def graph_by_slot(graph):
    return {record["slot"]: record for record in graph["steady_group_macs"]}


def boundary_hashes(graph) -> dict[int, str]:
    return {int(record["group"]): str(record["signature_hash"]) for record in graph["boundaries"]}


def format_cells(operand) -> str:
    parts: list[str] = []
    for cell in operand["cells"]:
        lane = cell["lane"] if cell["lane"] is not None else ""
        parts.append(f"{cell['cell']}:{cell['kind']}{lane}")
    return ", ".join(parts)


def graph_comment(record, section: str) -> str:
    return (
        f"// graph {section} from {record['slot']} "
        f"acc=[{format_cells(record['accumulator'])}] "
        f"left=[{format_cells(record['left'])}] "
        f"right=[{format_cells(record['right'])}]"
    )


def template_program(groups: dict[int, list]) -> list[GeneratedSlot]:
    program: list[GeneratedSlot] = []
    for slot in groups[0]:
        program.append(GeneratedSlot("fill", slot.text, slot.op, None))
    for repeat in range(STEADY_REPEATS):
        section = f"steady{repeat}"
        for slot in groups[1]:
            program.append(GeneratedSlot(section, slot.text, slot.op, slot_label(slot)))
    for slot in groups[6]:
        program.append(GeneratedSlot("pre_drain", slot.text, slot.op, None))
    for slot in groups[7]:
        program.append(GeneratedSlot("drain", slot.text, slot.op, None))
    return program


def render_asm_inc(program: list[GeneratedSlot], graph_records) -> tuple[str, tuple[str, ...], int]:
    missing: list[str] = []
    annotated_vmac = 0
    lines = [
        "// Generated by exp117 from exp115 operand graph JSON and MyLM templates.",
        "// Stripping comments must recover MyLM 0x260..0x1850 exactly.",
        "",
        ".macro MYLM_Q4NX_HOT_LOOP_GRAPH",
    ]
    previous_section = ""
    for slot in program:
        if slot.section != previous_section:
            lines.append(f"\t// section {slot.section}")
            previous_section = slot.section
        if slot.op == "vmac.f" and slot.group1_label is not None:
            record = graph_records.get(slot.group1_label)
            if record is None:
                missing.append(slot.group1_label)
            else:
                lines.append(f"\t{graph_comment(record, slot.section)}")
                annotated_vmac += 1
        lines.append(f"\t{slot.text}")
    lines.append(".endm")
    lines.append("")
    return "\n".join(lines), tuple(missing), annotated_vmac


def strip_generated_instructions(text: str) -> list[str]:
    instructions: list[str] = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("//") or line.startswith(".macro") or line == ".endm":
            continue
        instructions.append(line)
    return instructions


def validate(original_text: list[str], program: list[GeneratedSlot], graph, asm_text: str, missing: tuple[str, ...], annotated_vmac: int) -> FullGraphCheck:
    generated = strip_generated_instructions(asm_text)
    hashes = boundary_hashes(graph)
    op_counts: Counter[str] = Counter(slot.op for slot in program)
    steady_hashes = {hashes[group] for group in (2, 3, 4, 5, 6)}
    steady_hash = next(iter(steady_hashes)) if len(steady_hashes) == 1 else "unstable"
    return FullGraphCheck(
        original_slots=len(original_text),
        generated_slots=len(generated),
        original_hash=digest(original_text),
        generated_hash=digest(generated),
        exact_instruction_match=original_text == generated,
        graph_records=len(graph["steady_group_macs"]),
        annotated_vmac=annotated_vmac,
        missing_graph_records=missing,
        steady_boundary_hash=steady_hash,
        op_counts=op_counts,
    )


def render_report(check: FullGraphCheck, original_text: list[str], asm_text: str) -> str:
    generated = strip_generated_instructions(asm_text)
    key_ops = (
        "vmac.f",
        "vextbcst.16",
        "vunpack",
        "vups.4x",
        "vconv.bf16.fp32",
        "vst",
        "vlda",
        "vldb",
        "lda.s16",
        "vbcst.16",
    )
    lines = [
        "# MyLM Q4NX Full Graph Codegen",
        "",
        "This experiment expands the full MyLM Q4NX hot loop from templates and",
        "annotates the five steady sections using the exp115 operand graph.",
        "",
        "## Checks",
        "",
        f"- Original slots: `{check.original_slots}`",
        f"- Generated slots: `{check.generated_slots}`",
        f"- Original hash: `{check.original_hash}`",
        f"- Generated hash: `{check.generated_hash}`",
        f"- Instruction text match after stripping comments: `{check.exact_instruction_match}`",
        f"- Graph `vmac.f` records per steady group: `{check.graph_records}`",
        f"- Annotated steady `vmac.f`: `{check.annotated_vmac}`",
        f"- Missing graph records: `{len(check.missing_graph_records)}`",
        f"- Steady boundary hash: `{check.steady_boundary_hash}`",
        "",
        "## Opcode Counts",
        "",
        "| Op | Count |",
        "| --- | ---: |",
    ]
    for op in key_ops:
        lines.append(f"| `{op}` | {check.op_counts[op]} |")
    lines.extend(
        [
            "",
            "## Generated Include",
            "",
            f"- `{DEFAULT_ASM_INC}`",
            "",
            "## Production Boundary",
            "",
            "- The full hot loop now has a graph-annotated codegen artifact.",
            "- This is still MyLM's numerical contract; it is not the active IRON exact-Q4NX body.",
            "- The next step is to emit a modified graph-derived body and run a synthetic numeric gate before touching production.",
        ]
    )
    if check.missing_graph_records:
        lines.extend(["", "## Missing Records", ""])
        for item in check.missing_graph_records:
            lines.append(f"- `{item}`")
    if not check.exact_instruction_match:
        lines.extend(["", "## First Diff", "", "```diff"])
        lines.extend(list(unified_diff(original_text, generated, fromfile="mylm_hot_loop", tofile="generated", n=4))[:120])
        lines.append("```")
    return "\n".join(lines) + "\n"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--graph-json", type=Path, default=GRAPH_JSON)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--asm-inc", type=Path, default=DEFAULT_ASM_INC)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    exp104 = load_exp104()
    slots = exp104.parse_slots(exp104.DEFAULT_DISASM)
    groups = {group: [slot for slot in slots if slot.group == group] for group in range(8)}
    original_text = [slot.text for group in range(8) for slot in groups[group]]
    graph = load_graph(args.graph_json)
    program = template_program(groups)
    asm_text, missing, annotated_vmac = render_asm_inc(program, graph_by_slot(graph))
    check = validate(original_text, program, graph, asm_text, missing, annotated_vmac)
    args.asm_inc.write_text(asm_text)
    args.report.write_text(render_report(check, original_text, asm_text))
    print(f"wrote {args.report}")
    print(f"wrote {args.asm_inc}")
    print(f"original_slots={check.original_slots}")
    print(f"generated_slots={check.generated_slots}")
    print(f"exact_instruction_match={check.exact_instruction_match}")
    print(f"annotated_vmac={check.annotated_vmac}")
    print(f"steady_boundary_hash={check.steady_boundary_hash}")
    return 0 if check.exact_instruction_match and not check.missing_graph_records else 1


if __name__ == "__main__":
    raise SystemExit(main())
